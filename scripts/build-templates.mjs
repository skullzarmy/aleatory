/**
 * Turn the template files into the module the studio imports.
 *
 * The templates used to live as backtick literals inside templates.ts, which
 * had two costs. Nobody could find them, since a starting point for an artist
 * was buried in a TypeScript file they had no reason to open. And a single
 * backtick inside one of them ended the literal early and broke the module,
 * which has happened here already.
 *
 * So the files under public/templates are the source now. They are real HTML,
 * readable on GitHub, downloadable, and openable straight from disk in any
 * editor. This writes what the studio needs from them.
 *
 *   npm run templates:build
 *
 * Run automatically before a build, so a checked-in generated file that has
 * drifted from the templates cannot reach production.
 */

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

// Kept in step with RUNTIME_KINDS by the check below rather than by memory.
const KINDS = ["vanilla", "svg", "p5", "custom"];

const missing = KINDS.filter(
    (k) => !existsSync(join(root, "public/templates", k, "index.html")),
);
if (missing.length > 0) {
    console.error(`No template for: ${missing.join(", ")}`);
    process.exit(1);
}

const entries = KINDS.map((kind) => {
    const html = readFileSync(join(root, "public/templates", kind, "index.html"), "utf8");
    // JSON.stringify, not a template literal. That is the whole point: a
    // backtick or a ${ in someone's template can no longer end the string.
    return `    ${JSON.stringify(kind)}: ${JSON.stringify(html)},`;
}).join("\n");

const out = `// Generated by scripts/build-templates.mjs. Do not edit.
//
// The source is public/templates/<kind>/index.html. Edit those, then run
// \`npm run templates:build\`.

export const TEMPLATE_HTML: Record<string, string> = {
${entries}
};

export const TEMPLATE_KINDS = ${JSON.stringify(KINDS)} as const;
`;

const target = join(root, "src/lib/templates.generated.ts");
const previous = existsSync(target) ? readFileSync(target, "utf8") : "";
if (previous === out) {
    console.log("templates: already current");
} else {
    writeFileSync(target, out);
    console.log(`templates: wrote ${KINDS.length} into src/lib/templates.generated.ts`);
}
